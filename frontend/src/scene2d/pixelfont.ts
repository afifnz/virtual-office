/** A hollow box for characters the font does not define. */
const UNKNOWN_ROWS = [0b11111, 0b10001, 0b10001, 0b10001, 0b10001, 0b10001, 0b11111]

function toMask(row: string): number {
  let m = 0
  for (let c = 0; c < GLYPH_W; c++) {
    if (row[c] === '#') m |= 1 << (GLYPH_W - 1 - c)
  }
  return m
}

const GLYPHS: Map<string, Glyph> = new Map()
for (const [ch, rows] of Object.entries(RAW)) {
  GLYPHS.set(ch, { rows: rows.map(toMask) })
}

const UNKNOWN: Glyph = { rows: [...UNKNOWN_ROWS] }

/** Look up a glyph; input is uppercased, unknown characters get a hollow box. */
export function glyphFor(ch: string): Glyph {
  if (ch.length === 0) return UNKNOWN
  return GLYPHS.get(ch.toUpperCase()) ?? UNKNOWN
}

/** Deterministic text width in px (glyph advance × scale, last gap dropped). */
export function textWidth(text: string, scale = 1): number {
  if (text.length === 0) return 0
  return (text.length * ADVANCE - 1) * scale
}

function drawGlyph(
  ctx: CanvasRenderingContext2D,
  glyph: Glyph,
  x: number,
  y: number,
  scale: number,
  color: string,
): void {
  ctx.fillStyle = color
  for (let r = 0; r < GLYPH_H; r++) {
    const row = glyph.rows[r] ?? 0
    for (let c = 0; c < GLYPH_W; c++) {
      if (row & (1 << (GLYPH_W - 1 - c))) {
        ctx.fillRect(x + c * scale, y + r * scale, scale, scale)
      }
    }
  }
}

/**
 * Draw text top-left at (x, y) in pixel font. `scale` should stay an integer so
 * the glyphs keep their crisp nearest-neighbour edges.
 */
export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  scale = 1,
  color: string = PALETTE.ink,
): void {
  let cx = x
  for (const ch of text) {
    drawGlyph(ctx, glyphFor(ch), cx, y, scale, color)
    cx += ADVANCE * scale
  }
}
