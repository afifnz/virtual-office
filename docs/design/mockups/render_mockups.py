def glass(base: Image.Image, box, d: dict, radius: int = 12, blur: int = 16,
          alpha: float | None = None, shadow: bool = True) -> Image.Image:
    x0, y0, x1, y1 = [round(v) for v in box]
    w, h = x1 - x0, y1 - y0
    alpha = d["surface"][1] if alpha is None else alpha
    out = base.copy()
    if shadow:
        sh = Image.new("RGBA", (w + 80, h + 80), (0, 0, 0, 0))
        ImageDraw.Draw(sh).rounded_rectangle([40, 48, 40 + w, 48 + h], radius=radius,
                                             fill=(0, 0, 0, 80 if d["mode"] == "dark" else 72))
        comp(out, sh.filter(ImageFilter.GaussianBlur(20)), (x0 - 40, y0 - 40))
    region = base.crop((x0, y0, x1, y1)).filter(ImageFilter.GaussianBlur(blur))
    region = Image.blend(region, Image.new("RGB", (w, h), hex_rgb(d["surface"][0])), alpha)
    mask = Image.new("L", (w, h), 0)
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, w - 1, h - 1], radius=radius, fill=255)
    out.paste(region, (x0, y0), mask)

    hl = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    hd = ImageDraw.Draw(hl)
    hc = hex_rgb(d["highlight"]) + (int(255 * d["highlight_a"]),)
    hd.rounded_rectangle([0, 0, w - 1, h - 1], radius=radius, outline=hc, width=1)
    hd.line([(radius, 1), (w - radius, 1)],
            fill=hex_rgb(d["highlight"]) + (min(255, int(255 * d["highlight_a"] * 1.5)),), width=1)
    comp(out, hl, (x0, y0))
    ImageDraw.Draw(out, "RGBA").rounded_rectangle(
        [x0, y0, x1 - 1, y1 - 1], radius=radius,
        outline=hex_rgb(d["border"]) + (int(255 * d["border_a"]),), width=1)
    return out


