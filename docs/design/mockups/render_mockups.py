# --------------------------------------------------------------------- fonts
def font(size: float, bold: bool = False, mono: bool = False) -> ImageFont.FreeTypeFont:
    name = "DejaVuSansMono-Bold" if (mono and bold) else (
        "DejaVuSansMono" if mono else ("DejaVuSans-Bold" if bold else "DejaVuSans"))
    return ImageFont.truetype(str(FONT_DIR / f"{name}.ttf"), max(1, int(round(size))))


def load_pixel_font() -> dict[str, int]:
    src = (REPO / "frontend/src/scene2d/pixelfont.ts").read_text()
    raw = re.search(r"const RAW: Record<string, Row\[\]> = \{(.*?)\n\}", src, re.S)
    glyphs: dict[str, int] = {}
    for ch, word, rows in re.findall(r"(?:'(.)'|(\w)):\s*\[([^\]]+)\]", raw.group(1) if raw else ""):
        bits = 0
        for r in re.findall(r"'([.#]+)'", rows):
            bits = (bits << 5) | sum(1 << (4 - i) for i, c in enumerate(r) if c == "#")
        glyphs[ch or word] = bits
    return glyphs


PIXEL = load_pixel_font()


def pixel_text(d: ImageDraw.ImageDraw, text: str, x: int, y: int, scale: int, color) -> int:
    cx = x
    for ch in text.upper():
        bits = PIXEL.get(ch, PIXEL.get("?", 0))
        for row in range(7):
            for col in range(5):
                if bits >> (5 * (6 - row) + (4 - col)) & 1:
                    d.rectangle([cx + col * scale, y + row * scale,
                                 cx + col * scale + scale - 1, y + row * scale + scale - 1], fill=color)
        cx += 6 * scale
    return cx - x


def pixel_width(text: str, scale: int) -> int:
    return len(text) * 6 * scale - scale


# --------------------------------------------------------------------- paint

def comp(img: Image.Image, layer: Image.Image, pos=(0, 0)) -> None:
    """Alpha-composite onto a base of either mode (the scene canvas may be RGB)."""
    if img.mode == "RGBA":
        img.alpha_composite(layer, pos)
    else:
        img.paste(layer, pos, layer)

def lin_grad(size, c0: str, c1: str, horizontal: bool = False) -> Image.Image:
    w, h = size
    img = Image.new("RGB", (w, h))
    d = ImageDraw.Draw(img)
    a, b = hex_rgb(c0), hex_rgb(c1)
    n = w if horizontal else h
    for i in range(n):
        t = i / max(1, n - 1)
        col = tuple(round(a[j] + (b[j] - a[j]) * t) for j in range(3))
        if horizontal:
            d.line([(i, 0), (i, h)], fill=col)
        else:
            d.line([(0, i), (w, i)], fill=col)
    return img


def paint_grad(target: Image.Image, mask: Image.Image, c0: str, c1: str, horizontal: bool = False):
    target.paste(lin_grad(target.size, c0, c1, horizontal), (0, 0), mask)


def shade(c: str, k: float) -> str:
    """k < 1 darkens toward black, k > 1 lightens toward white."""
    r, g, b = hex_rgb(c)
    if k <= 1:
        return "#%02X%02X%02X" % (round(r * k), round(g * k), round(b * k))
    t = k - 1
    return "#%02X%02X%02X" % (round(r + (255 - r) * t), round(g + (255 - g) * t), round(b + (255 - b) * t))


def rr(d, box, r, **kw):
    d.rounded_rectangle([round(v) for v in box], radius=max(1, round(r)), **kw)


